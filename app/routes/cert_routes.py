# 3. STUDENT COURSE CERTIFICATE RETRIEVAL & STATUS CHECK
# ===================================================================

@router.get("/course/{course_id}/certificate", response_class=HTMLResponse)
async def student_course_certificate(request: Request, course_id: int):
    """
    Checks if a student has an officially issued certificate by the Admin.
    - If not completed: displays 'Course Not Completed' error/explanation.
    - If completed but not yet generated by Admin: displays 'Course Completed - Certificate Pending Admin Approval'.
    - If generated by Admin: displays/redirects to the authentic verified certificate.
    """
    user = get_current_user(request)
    if not user:
        return RedirectResponse(url="/login", status_code=303)

    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM courses WHERE id = ? AND status = 'published' AND deleted_at IS NULL", (course_id,))
        course = cursor.fetchone()
        if not course:
            raise HTTPException(status_code=404, detail="Course not found or has been removed from LMS")

        # 1. Check if an authentic certificate has already been issued by the Admin
        cursor.execute("""
            SELECT * FROM certificates 
            WHERE student_id = ? AND course_id = ? AND status != 'revoked'
            ORDER BY issued_at DESC, id DESC LIMIT 1
        """, (user["id"], course_id))
        cert = cursor.fetchone()
        if cert:
            return RedirectResponse(url=f"/certificate/{cert['certificate_id']}", status_code=303)

        # 2. Check student's actual lesson progress for this course
        cursor.execute("""
            SELECT 
                (SELECT COUNT(*) FROM lessons l JOIN modules m ON l.module_id = m.id WHERE m.course_id = ?) as total,
                (SELECT COUNT(*) FROM lesson_progress lp 
                 JOIN lessons l ON lp.lesson_id = l.id 
                 JOIN modules m ON l.module_id = m.id 
                 WHERE m.course_id = ? AND lp.user_id = ? AND lp.is_completed = 1) as completed
        """, (course_id, course_id, user["id"]))
        comp = cursor.fetchone()
        total_lessons = comp[0] if comp else 0
        completed_lessons = comp[1] if comp else 0
        progress_pct = round((completed_lessons / total_lessons * 100) if total_lessons > 0 else 0)

        # 3. If student has not completed the course:
        if total_lessons == 0 or completed_lessons < total_lessons:
            return templates.TemplateResponse("course_certificate_status.html", {
                "request": request,
                "user": user,
                "course": dict(course),
                "status": "not_completed",
                "total_lessons": total_lessons,
                "completed_lessons": completed_lessons,
                "progress_percent": progress_pct
            })

        # 4. Student has completed 100%, but Admin has not generated the certificate yet!
        return templates.TemplateResponse("course_certificate_status.html", {
            "request": request,
            "user": user,
            "course": dict(course),
            "status": "pending_admin_approval",
            "total_lessons": total_lessons,
            "completed_lessons": completed_lessons,
            "progress_percent": 100
        })

