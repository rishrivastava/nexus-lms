@router.post("/api/certificates/issue")
async def issue_certificate_api(
    request: Request,
    student_id: int = Form(...),
    course_id: int = Form(...),
    completion_date: Optional[str] = Form(None),
    grade_score: Optional[float] = Form(100.0)
):
    """Admins can manually issue an authentic certificate to any student for a course."""
    admin = require_admin(request)
    try:
        cert = issue_certificate(
            student_id=student_id,
            course_id=course_id,
            admin_user_id=admin["id"],
            completion_date=completion_date,
            grade_score=grade_score
        )
        # Notify the student immediately
        course_title = cert.get('course_title') or cert.get('course_name') or 'Course'
        notify_users(
            [student_id],
            f"Certificate Issued: {course_title}",
            f"Your official completion certificate for '{course_title}' has been generated by the Administrator. Certificate ID: {cert['certificate_id']}.",
            link=f"/certificate/{cert['certificate_id']}",
            category="certificate",
            event_type="certificate_issued"
        )
        return JSONResponse({"status": "success", "message": "Certificate issued successfully", "data": cert})
    except Exception as e:
        raise HTTPException(status_code=400, detail=str(e))

